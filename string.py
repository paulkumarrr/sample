text=input("Enter the text:")
print("\n---DISPLAYING THE FIRST AND LAST CHARACTER OF TEXT---")
print("First character of text  :",text[0])
print("Last character of text   :",text[-1])
print("text at 5th position     :",text[4])
print("\n---DISPLAYING THE FIRST FIVE AND LAST THREE CHARACTERS OF TEXT AND REVERSING THE TEXT---")
print("First five characters of text:",text[:5:1])
print("Last three characters of text:",text[-3])
print("Last two characters of the text:",text[-2])
print("Reversing the text       :",text[::-1])
print("\n---DISPLAYING UPPERCASE, LOWERCASE AND LENGTH OF THE TEXT---")
print("Uppercase of the text    :",text.upper())
print("Lowercase of the text    :",text.lower())
print("Length of the text       :",len(text))
